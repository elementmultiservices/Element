"use client";

import { useState, useTransition } from "react";
import { useTranslations } from "next-intl";
import { Loader2 } from "lucide-react";
import { startMfaEnrollmentAction, verifyMfaAction, type MfaEnrollment, type MfaField } from "@/actions/auth";
import { FormAlert } from "@/components/forms/form-alert";
import { FormField } from "@/components/forms/form-field";
import { SubmitButton } from "@/components/forms/submit-button";
import { Button } from "@/components/ui/button";
import { useProtectedAction } from "@/hooks/use-protected-action";

function CodeForm({ factorId }: { factorId?: string }) {
  const t = useTranslations("Auth.mfa");
  const tv = useTranslations("Validation");
  const te = useTranslations("Errors");
  const { state, onSubmit, pending } = useProtectedAction<MfaField>(verifyMfaAction);

  return (
    <form onSubmit={onSubmit} noValidate className="space-y-5">
      {state.error ? <FormAlert variant="error">{te(state.error)}</FormAlert> : null}
      {factorId ? <input type="hidden" name="factorId" value={factorId} /> : null}
      <FormField
        name="code"
        label={t("code")}
        inputMode="numeric"
        autoComplete="one-time-code"
        pattern="[0-9]{6}"
        maxLength={6}
        required
        className="max-w-48"
        error={state.fieldErrors?.code ? tv(state.fieldErrors.code) : undefined}
      />
      <SubmitButton pending={pending} label={t("verify")} pendingLabel={t("verifying")} />
    </form>
  );
}

export function MfaVerify() {
  return <CodeForm />;
}

export function MfaEnroll() {
  const t = useTranslations("Auth.mfa");
  const te = useTranslations("Errors");
  const [enrollment, setEnrollment] = useState<MfaEnrollment | null>(null);
  const [isPending, startTransition] = useTransition();

  if (enrollment?.ok) {
    return (
      <div className="space-y-5">
        <div className="flex justify-center rounded-md border bg-white p-4">
          {/* eslint-disable-next-line @next/next/no-img-element -- data URI generated by Supabase Auth */}
          <img src={enrollment.qrCode} alt={t("qrAlt")} width={192} height={192} />
        </div>
        <div className="text-sm">
          <p className="text-muted-foreground">{t("manualKey")}</p>
          <code className="mt-1 block rounded-sm bg-muted px-2 py-1.5 font-mono text-xs break-all">{enrollment.secret}</code>
        </div>
        <CodeForm factorId={enrollment.factorId} />
      </div>
    );
  }

  return (
    <div className="space-y-4">
      {enrollment && !enrollment.ok ? <FormAlert variant="error">{te("generic")}</FormAlert> : null}
      <Button
        type="button"
        className="h-10 w-full"
        disabled={isPending}
        onClick={() => startTransition(async () => setEnrollment(await startMfaEnrollmentAction()))}
      >
        {isPending ? <Loader2 aria-hidden="true" className="animate-spin" /> : null}
        {isPending ? t("starting") : t("start")}
      </Button>
    </div>
  );
}
